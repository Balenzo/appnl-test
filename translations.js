function normalizeLanguage(language) {
  return BALENZO_SUPPORTED_LANGUAGES.includes(language)
    ? language
    : BALENZO_DEFAULT_LANGUAGE;
}

let currentLanguage = normalizeLanguage(
  localStorage.getItem(BALENZO_LANGUAGE_STORAGE_KEY) ||
  BALENZO_DEFAULT_LANGUAGE
);

function getCurrentLanguage() {
  return currentLanguage;
}

function getLocale() {
  const locales = {
    nl: "nl-BE",
    en: "en-GB",
    fr: "fr-BE"
  };

  return locales[currentLanguage] || locales.nl;
}

function setLanguage(language) {
  currentLanguage = normalizeLanguage(language);

  localStorage.setItem(
    BALENZO_LANGUAGE_STORAGE_KEY,
    currentLanguage
  );

  document.documentElement.lang = currentLanguage;
}

function changeAppLanguage(language) {
  setLanguage(language);
  window.location.reload();
}

function t(key, params = {}) {
  const languageTable =
    translations[currentLanguage] || translations.nl;

  let value =
    languageTable?.[key] ??
    translations.nl?.[key] ??
    key;

  Object.entries(params).forEach(([name, replacement]) => {
    value = value.replaceAll(
      `{{${name}}}`,
      String(replacement)
    );
  });

  return value;
}

function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (!key) return;

    const translated = t(key);

    // Bij een ontbrekende key laten we de bestaande fallbacktekst staan.
    if (translated !== key) {
      element.textContent = translated;
    }
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    if (!key) return;

    const translated = t(key);
    if (translated !== key) {
      element.setAttribute("placeholder", translated);
    }
  });

  root.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    const key = element.dataset.i18nAriaLabel;
    if (!key) return;

    const translated = t(key);
    if (translated !== key) {
      element.setAttribute("aria-label", translated);
    }
  });

  root.querySelectorAll("[data-i18n-title]").forEach(element => {
    const key = element.dataset.i18nTitle;
    if (!key) return;

    const translated = t(key);
    if (translated !== key) {
      element.setAttribute("title", translated);
    }
  });
}

function syncLanguageSelector() {
  const selector = document.getElementById("languageSelector");

  if (selector) {
    selector.value = currentLanguage;
  }
}

setLanguage(currentLanguage);

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  syncLanguageSelector();
});
